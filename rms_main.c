float compute_rms(const int32_t *samples, size_t n)
{
	float sum_sq = 0.0f;
    size_t active_samples = n / 2;

    // Step by 2 to isolate the Left channel (even indices)
    for (size_t i = 0; i < n; i += 2)
    {
        int32_t s = samples[i];

        // Arithmetic shift to accurately sign-extend the 24-bit microphone data
        s = (s << 8) >> 8;

        // 1. Convert to float
        float x = (float)s;

        // 2. High-pass filter (DC blocker equation: y[n] = x[n] - x[n-1] + R * y[n-1])
        float y = x - dc_prev_x + (FILTER_R * dc_prev_y);

        // 3. Update history states
        dc_prev_x = x;
        dc_prev_y = y;

        // 4. Accumulate squared AC components
        sum_sq += (y * y);
    }

    return sqrtf(sum_sq / (float)active_samples);
}
